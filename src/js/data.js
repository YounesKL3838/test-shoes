export function formatDA(amount, lang = 'fr') {
  if (lang === 'ar') {
    return `${new Intl.NumberFormat('fr-DZ').format(amount)} د.ج`;
  }
  return `${new Intl.NumberFormat('fr-DZ').format(amount)} DA`;
}
